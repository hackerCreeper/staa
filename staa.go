func Convert(si string) Banner {
	const height = 5

	lines := make(Banner, height)

	for i := 0; i < len(si); i++ {
		char := si[i]

		art, exists := asciiArt[char]
		if !exists {
			art = []string{" [?] ", " [?] ", " [?] ", " [?] ", " [?] "}
		}

		for lineIdx := 0; lineIdx < height; lineIdx++ {
			lines[lineIdx] += art[lineIdx] + " "
		}
	}

	return lines
}

func (b Banner) Print() {
	for _, line := range b {
		fmt.Println(line)
	}
}
